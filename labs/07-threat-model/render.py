def render_controls(m: ThreatModel) -> str:
    ranked = rank_controls(m)
    lines = [
        "# Control checklist -- reference agent architecture",
        "",
        "Generated by `labs/07-threat-model/render.py` from the threat model. Do not edit by",
        "hand: change `reference_model.py` and re-run `python run_demo.py`.",
        "",
        "Ranked by the highest likelihood x impact among the threats each control treats",
        "(illustrative scoring, 1-25). The Post 17 red-team ticks a box only when an attack",
        "that targets the control has been run and driven to ~0% success.",
        "",
        "| Rank | | Control | Score | Treats | OWASP | Verify in |",
        "|---:|:-:|---|---:|---|---|---|",
    ]
    for r in ranked:
        lines.append(f"| {r.rank} | [ ] | **{r.id}** {r.name} | {r.score} | "
                     f"{', '.join(r.threats)} | {', '.join(r.owasp)} | "
                     f"{', '.join(r.verify_in)} |")
    lines += ["", "## Checklist", ""]
    for r in ranked:
        c = m.control(r.id)
        lines.append(f"- [ ] **{r.id}** {r.name} (score {r.score}) -- {c.description}")
    if m.owasp_accepted:
        lines += ["", "## Explicitly accepted OWASP items", ""]
        for item, reason in sorted(m.owasp_accepted.items()):
            lines.append(f"- **{item} {ALL_OWASP.get(item, '')}** -- {reason}")
    return "\n".join(lines) + "\n"


def render_threats(m: ThreatModel) -> str:
    lines = ["# Threat register", "",
             "| Id | STRIDE | Threat | Targets | L | I | Risk | Controls | OWASP | ATLAS tactic |",
             "|---|:-:|---|---|:-:|:-:|:-:|---|---|---|"]
    for t in sorted(m.threats, key=lambda t: (-t.risk, t.id)):
        targets = ", ".join(t.targets) if len(t.targets) <= 4 else f"{len(t.targets)} flows"
        lines.append(f"| {t.id} | {t.stride} | {t.title} | {targets} | {t.likelihood} | "
                     f"{t.impact} | {t.risk} | {', '.join(t.controls)} | "
                     f"{', '.join(t.owasp)} | {', '.join(t.atlas)} |")
    lines += ["", "## STRIDE per element", "",
              "Each cell is the number of threats recorded for that letter. `n/a` = letter does",
              "not apply to this element type; `na*` = considered and ruled out with a reason.", "",
              "| Element | Kind | " + " | ".join(STRIDE) + " |",
              "|---|---|" + ":-:|" * len(STRIDE)]
    elements = [(c.id, c.kind) for c in m.components] + [(f.id, "flow") for f in m.flows]
    for eid, kind in elements:
        cells = []
        for letter in STRIDE:
            if letter not in STRIDE_PER_ELEMENT[kind]:
                cells.append("n/a")
            elif (eid, letter) in m.stride_na:
                cells.append("na*")
            else:
                cells.append(str(len(m.threats_on(eid, letter))))
        lines.append(f"| {eid} | {kind} | " + " | ".join(cells) + " |")
    if m.stride_na:
        lines += ["", "Ruled out:", ""]
        for (eid, letter), reason in sorted(m.stride_na.items()):
            lines.append(f"- `{eid}` {STRIDE[letter][0]}: {reason}")
    return "\n".join(lines) + "\n"


def write_all(m: ThreatModel, tree: Node, implemented: set[str],
              out_dir: str = OUT_DIR, suffix: str = "") -> dict[str, str]:
    """Write every artifact; return {name: path}."""
    os.makedirs(out_dir, exist_ok=True)
    files = {
        f"architecture-threats{suffix}.mmd": render_dfd(m, tree),
        f"attack-tree{suffix}.mmd": tree_mermaid(tree, implemented),
        f"attack-tree{suffix}.txt": tree_text(tree, implemented) + "\n",
        f"controls{suffix}.md": render_controls(m),
        f"threats{suffix}.md": render_threats(m),
    }
    from checklist import checklist_from_model
    files[f"controls{suffix}.json"] = json.dumps(
        [item.__dict__ for item in checklist_from_model(m)], indent=2) + "\n"
    paths = {}
    for name, text in files.items():
        path = os.path.join(out_dir, name)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
        paths[name] = path
    return paths
